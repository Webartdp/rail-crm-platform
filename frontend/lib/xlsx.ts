/**
 * Minimal Excel (.xlsx) writer without dependencies: one or more sheets with text,
 * numbers, bold header rows and column widths. Files are zipped with the "store" method.
 */

export type Cell = string | number | null | undefined | { value: string | number | null | undefined; bold?: boolean; format?: 'hours' | 'money' };
export type Sheet = { name: string; rows: Cell[][]; widths?: number[] };

const encoder = new TextEncoder();

function escapeXml(value: string) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    // characters not allowed in XML 1.0
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');
}

function columnName(index: number) {
  let name = '';
  let n = index + 1;
  while (n > 0) {
    const rest = (n - 1) % 26;
    name = String.fromCharCode(65 + rest) + name;
    n = Math.floor((n - 1) / 26);
  }
  return name;
}

// Style ids, see styles() below.
const STYLE = { normal: 0, bold: 1, hours: 2, boldHours: 3, money: 4, boldMoney: 5 };

function cellXml(cell: Cell, ref: string) {
  const spec = cell !== null && typeof cell === 'object' ? cell : { value: cell };
  const { value } = spec;
  if (value === null || value === undefined || value === '') return '';

  let style = spec.bold ? STYLE.bold : STYLE.normal;
  if (typeof value === 'number' && Number.isFinite(value)) {
    if (spec.format === 'hours') style = spec.bold ? STYLE.boldHours : STYLE.hours;
    if (spec.format === 'money') style = spec.bold ? STYLE.boldMoney : STYLE.money;
    return `<c r="${ref}" s="${style}"><v>${value}</v></c>`;
  }
  return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${escapeXml(String(value))}</t></is></c>`;
}

function sheetXml(sheet: Sheet) {
  const cols = sheet.widths?.length
    ? `<cols>${sheet.widths.map((width, index) => `<col min="${index + 1}" max="${index + 1}" width="${width}" customWidth="1"/>`).join('')}</cols>`
    : '';
  const rows = sheet.rows
    .map((row, rowIndex) => `<row r="${rowIndex + 1}">${row.map((cell, colIndex) => cellXml(cell, `${columnName(colIndex)}${rowIndex + 1}`)).join('')}</row>`)
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"/></sheetViews>${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

